from datetime import datetime
from pathlib import Path

from fpdf import FPDF
from fpdf.fonts import FontFace


NAVY = (30, 41, 59)
LIGHT = (241, 245, 249)
MUTED = (100, 116, 139)
WHITE = (255, 255, 255)
STATE_COLORS = {
    "open": (22, 163, 74),
    "closed": (148, 163, 184),
    "filtered": (217, 119, 6),
}

# porturi care merita verificate daca sunt deschise
SENSITIVE_PORTS = {
    21: "FTP - credentials travel in clear text",
    23: "Telnet - unencrypted remote shell",
    25: "SMTP - check that it is not an open relay",
    445: "SMB - frequent target of worms and exploits",
    1433: "MS SQL Server - databases should not be exposed",
    3306: "MySQL - databases should not be exposed",
    3389: "RDP - remote desktop, common brute-force target",
    5432: "PostgreSQL - databases should not be exposed",
    5900: "VNC / Screen Sharing - remote control of the machine",
    6379: "Redis - often runs without authentication",
    27017: "MongoDB - often runs without authentication",
    33060: "MySQL X Protocol - databases should not be exposed",
}

# folderul reports/ din radacina proiectului, indiferent din ce folder rulezi
REPORTS_DIR = Path(__file__).resolve().parent.parent / "reports"

PAGE_WIDTH = 210
MARGIN = 15
CONTENT_WIDTH = PAGE_WIDTH - 2 * MARGIN


class ReportPDF(FPDF):
    def footer(self):
        self.set_y(-12)
        self.set_font("Helvetica", size=8)
        self.set_text_color(*MUTED)
        self.cell(0, 5, "Generated by Port_Scanner - scan only targets you are authorized to test")
        self.set_x(MARGIN)
        self.cell(0, 5, f"Page {self.page_no()}/{{nb}}", align="R")


def clean_text(text, max_len=90):
    # pastreaza doar caracterele ASCII printabile (bannerele binare au octeti de control)
    if not text:
        return "-"
    printable = "".join(ch if ch.isprintable() and ord(ch) < 128 else " " for ch in text)
    printable = " ".join(printable.split())
    if len(printable) > max_len:
        printable = printable[:max_len - 3] + "..."
    return printable or "-"


def count_states(results):
    counts = {"open": 0, "closed": 0, "filtered": 0}
    for result in results:
        counts[result["state"]] += 1
    return counts


def section_title(pdf, title):
    pdf.ln(6)
    pdf.set_font("Helvetica", "B", 13)
    pdf.set_text_color(*NAVY)
    pdf.cell(0, 8, title, new_x="LMARGIN", new_y="NEXT")
    pdf.set_fill_color(*STATE_COLORS["open"])
    pdf.rect(MARGIN, pdf.get_y(), 18, 0.8, "F")
    pdf.ln(4)


def draw_header(pdf, host, scan_date):
    pdf.set_fill_color(*NAVY)
    pdf.rect(0, 0, PAGE_WIDTH, 38, "F")
    pdf.set_xy(MARGIN, 11)
    pdf.set_font("Helvetica", "B", 22)
    pdf.set_text_color(*WHITE)
    pdf.cell(0, 10, "Port Scan Report", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", size=10)
    pdf.set_text_color(203, 213, 225)
    pdf.cell(0, 7, f"Target: {host}     |     {scan_date:%d %B %Y, %H:%M}")
    pdf.set_y(44)


def draw_scan_details(pdf, host, ports, timeout, max_workers, duration):
    section_title(pdf, "Scan details")
    duration_text = f"{duration:.1f} s" if duration is not None else "-"
    details = [
        ("Target", host),
        ("Ports scanned", f"{min(ports)} - {max(ports)}  ({len(ports):,} ports)"),
        ("Timeout per port", f"{timeout} s"),
        ("Threads", str(max_workers)),
        ("Duration", duration_text),
        ("Scan type", "TCP connect"),
    ]
    half = CONTENT_WIDTH / 2
    pdf.set_fill_color(*LIGHT)
    pdf.rect(MARGIN, pdf.get_y(), CONTENT_WIDTH, 3 * 8 + 4, "F")
    top = pdf.get_y() + 2
    for index, (label, value) in enumerate(details):
        x = MARGIN + 4 + (index % 2) * half
        y = top + (index // 2) * 8
        pdf.set_xy(x, y)
        pdf.set_font("Helvetica", size=9)
        pdf.set_text_color(*MUTED)
        pdf.cell(32, 8, label)
        pdf.set_font("Helvetica", "B", 10)
        pdf.set_text_color(*NAVY)
        pdf.cell(half - 36, 8, value)
    pdf.set_y(top + 3 * 8 + 2)


def draw_summary(pdf, counts):
    section_title(pdf, "Summary")
    total = sum(counts.values())
    cards = [
        ("Total scanned", total, NAVY),
        ("Open", counts["open"], STATE_COLORS["open"]),
        ("Closed", counts["closed"], STATE_COLORS["closed"]),
        ("Filtered", counts["filtered"], STATE_COLORS["filtered"]),
    ]
    gap = 4
    card_width = (CONTENT_WIDTH - 3 * gap) / 4
    top = pdf.get_y()
    for index, (label, value, color) in enumerate(cards):
        x = MARGIN + index * (card_width + gap)
        pdf.set_fill_color(*LIGHT)
        pdf.rect(x, top, card_width, 26, "F")
        pdf.set_fill_color(*color)
        pdf.rect(x, top, 1.5, 26, "F")
        pdf.set_xy(x + 5, top + 3)
        pdf.set_font("Helvetica", "B", 18)
        pdf.set_text_color(*color)
        pdf.cell(card_width - 6, 10, f"{value:,}")
        pdf.set_xy(x + 5, top + 13)
        pdf.set_font("Helvetica", size=9)
        pdf.set_text_color(*NAVY)
        pdf.cell(card_width - 6, 5, label)
        if label != "Total scanned":
            pdf.set_xy(x + 5, top + 18)
            pdf.set_text_color(*MUTED)
            pdf.cell(card_width - 6, 5, f"{value / total:.2%} of total")
    pdf.set_y(top + 32)

    open_share = counts["open"] / total
    pdf.set_font("Helvetica", size=10)
    pdf.set_text_color(*NAVY)
    pdf.multi_cell(
        0, 6,
        f"**{counts['open']:,} of {total:,}** scanned ports are open ({open_share:.2%}).",
        markdown=True, new_x="LMARGIN", new_y="NEXT",
    )
    pdf.ln(2)

    # bara proportionala: fiecare stare ocupa latimea corespunzatoare procentului ei
    x = MARGIN
    bar_top = pdf.get_y()
    for state in ("open", "filtered", "closed"):
        if counts[state] == 0:
            continue
        width = max(CONTENT_WIDTH * counts[state] / total, 1.2)
        width = min(width, MARGIN + CONTENT_WIDTH - x)
        pdf.set_fill_color(*STATE_COLORS[state])
        pdf.rect(x, bar_top, width, 5, "F")
        x += width
    pdf.set_y(bar_top + 8)
    pdf.set_font("Helvetica", size=8)
    for state in ("open", "filtered", "closed"):
        pdf.set_fill_color(*STATE_COLORS[state])
        pdf.rect(pdf.get_x(), pdf.get_y() + 1.5, 3, 3, "F")
        pdf.set_x(pdf.get_x() + 4)
        pdf.set_text_color(*MUTED)
        pdf.cell(28, 6, state.capitalize())
    pdf.ln(6)


def draw_open_ports(pdf, open_ports):
    section_title(pdf, "Open ports")
    if not open_ports:
        pdf.set_font("Helvetica", size=10)
        pdf.set_text_color(*MUTED)
        pdf.cell(0, 8, "No open ports were found.", new_x="LMARGIN", new_y="NEXT")
        return
    pdf.set_font("Helvetica", size=9)
    pdf.set_text_color(*NAVY)
    # randurile fara fundal folosesc culoarea de umplere curenta, deci o resetam la alb
    pdf.set_fill_color(*WHITE)
    with pdf.table(
        col_widths=(18, 38, 124),
        text_align=("CENTER", "LEFT", "LEFT"),
        headings_style=FontFace(emphasis="BOLD", color=WHITE, fill_color=NAVY),
        cell_fill_color=LIGHT,
        cell_fill_mode="ROWS",
        borders_layout="NONE",
        line_height=6,
        padding=1.5,
    ) as table:
        table.row(("Port", "Service", "Banner"))
        for result in open_ports:
            table.row((
                str(result["port"]),
                clean_text(result.get("service")),
                clean_text(result.get("banner")),
            ))


def draw_notable_services(pdf, open_ports):
    section_title(pdf, "Services worth reviewing")
    notable = [result for result in open_ports if result["port"] in SENSITIVE_PORTS]
    pdf.set_font("Helvetica", size=10)
    if not notable:
        pdf.set_text_color(*MUTED)
        pdf.cell(0, 8, "No commonly sensitive services were found among the open ports.")
        return
    for result in notable:
        pdf.set_fill_color(*STATE_COLORS["filtered"])
        pdf.rect(MARGIN, pdf.get_y() + 2, 2.5, 2.5, "F")
        pdf.set_x(MARGIN + 5)
        pdf.set_text_color(*NAVY)
        pdf.multi_cell(
            0, 6.5,
            f"**Port {result['port']}** ({clean_text(result.get('service'))}): "
            f"{SENSITIVE_PORTS[result['port']]}",
            markdown=True, new_x="LMARGIN", new_y="NEXT",
        )
    pdf.ln(1)
    pdf.set_font("Helvetica", "I", 8)
    pdf.set_text_color(*MUTED)
    pdf.multi_cell(
        0, 5,
        "An open port is not a vulnerability by itself. Check whether each service is needed, "
        "up to date, and reachable only from the networks that should use it.",
        align="L",
    )


def generate_pdf(results, host, ports, timeout, max_workers, duration=None,
                 output_path=None):
    open_ports = [result for result in results if result["state"] == "open"]
    counts = count_states(results)
    scan_date = datetime.now()
    if output_path is None:
        REPORTS_DIR.mkdir(exist_ok=True)
        output_path = REPORTS_DIR / f"{scan_date:%Y-%m-%d_%H-%M-%S}_portscan.pdf"

    pdf = ReportPDF(format="A4")
    pdf.set_margins(MARGIN, MARGIN, MARGIN)
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.set_title(f"Port Scan Report - {host}")
    pdf.add_page()

    draw_header(pdf, host, scan_date)
    draw_scan_details(pdf, host, ports, timeout, max_workers, duration)
    draw_summary(pdf, counts)
    draw_open_ports(pdf, open_ports)
    draw_notable_services(pdf, open_ports)

    pdf.output(output_path)
    return output_path
